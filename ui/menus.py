    def show_help(self, back: Callable[[], None]) -> None:
        self._back_target = back
        self._show(self.help)

    # ================================================================== end screen
    def _build_end(self) -> None:
        s = self.end = Screen(dim=0.55)
        p = s.panel((1.0, 0.76))
        self.end_title = Text(parent=p, text="", position=(0, 0.31, -0.01), origin=(0, 0), scale=3.0, color=GOLD)
        self.end_sub = label(p, "", (0, 0.245), 0.95, DIM, origin=(0, 0))
        self.end_stars = Text(parent=p, text="", position=(0, 0.195, -0.01), origin=(0, 0), scale=2.6)
        self.end_rows: list[tuple[Text, Text]] = []
        y = 0.13
        for _ in range(8):
            self.end_rows.append((label(p, "", (-0.32, y), 0.92, DIM), label(p, "", (0.32, y), 0.92, TEXT, origin=(0.5, 0.5))))
            y -= 0.04
        self.end_score = label(p, "", (0, -0.21), 1.5, GOLD, origin=(0, 0))
        self.end_best = label(p, "", (0, -0.255), 0.85, DIM, origin=(0, 0))
        self.end_main = make_button(p, "Main Menu", (-0.32, -0.325), (0.26, 0.06), self.quit_to_main)
        self.end_again = make_button(p, "Play Again", (0.0, -0.325), (0.26, 0.06), self.restart, col=color.rgba(0.45, 0.25, 0.06, 1))
        self.end_more = make_button(p, "Keep Going (Endless)", (0.32, -0.325), (0.3, 0.06), self._continue_endless)

    def _on_match_over(self, match=None, won: bool = False, **_: Any) -> None:
        g = self.game
        m = g.match
        if m is None or m is not match or m.config.demo:
            return
        g.state = "ended"

        def show() -> None:
            if g.match is m and m.over:
                self.show_end(m)

        invoke(show, delay=2.2)       # real seconds: the field keeps playing in slow motion meanwhile

    def show_end(self, m) -> None:
        g = self.game
        won = m.won
        entry, is_best = scores.record(m)
        self.end_title.text = "Victory!" if won else "The Heartfire is out"
        self.end_title.color = GOLD if won else color.rgb(0.85, 0.3, 0.25)
        t = int(m.time)
        mode = "Endless" if m.config.endless else "30 waves"
        self.end_sub.text = f"{m.level.name}  -  {m.diff['name']}  -  {mode}  -  {t // 60}:{t % 60:02d}"
        self.end_stars.text = star_text(entry["stars"]) if (won and not m.config.endless) else ""
        best_tower = max(m.towers, key=lambda tw: tw.damage_dealt, default=None)
        rows = [("Waves cleared", str(len(m.waves.cleared))), ("Creeps slain", str(m.stats["kills"])),
                ("Creeps leaked", str(m.stats["leaks"])), ("Lives left", f"{max(0, m.lives)} / {m.max_lives}"),
                ("Gold earned", str(m.stats["gold_earned"])),
                ("Towers built / upgrades", f"{m.stats['towers_built']} / {m.stats['upgrades']}"),
                ("Powers used", str(m.stats["spells"])),
                ("Best tower", f"{best_tower.name}: {int(best_tower.damage_dealt):,} dmg" if best_tower else "-")]
        for (a, b), (t0, t1) in zip(rows, self.end_rows):
            t0.text, t1.text = a, b
        self.end_score.text = f"Score  {entry['score']}"
        prev = scores.best(m.config.map_id, m.config.difficulty, m.config.endless)
        self.end_best.text = "A new personal best!" if is_best else f"Personal best: {prev.get('score', 0) if prev else 0}"
        more = bool(won and not m.config.endless)
        self.end_more.enabled = more
        self.end_main.x = -0.32 if more else -0.16
        self.end_again.x = 0.0 if more else 0.16
        if g.hud is not None:
            g.hud.set_visible(False)
        self._show(self.end)
        events.emit("sound", name="victory" if won else "defeat")

    def _continue_endless(self) -> None:
        g = self.game
        m = g.match
        if m is None or not m.won:
            return
        m.config.endless = True
        m.waves.endless = True
        m.waves.finished = False
        m.over = False
        m.won = False
        g.state = "playing"
        self.close()
        if g.hud is not None:
            g.hud.attach(m)
